#!/usr/bin/env python3
"""Build every ready lean-eval payload from the repository's source modules.

The public lean-eval submission service recursively discovers directories whose
``lakefile.toml`` name is a problem id.  It copies only ``Submission.lean`` and
``Submission/**/*.lean`` from each discovered directory onto a pristine copy of
that problem's workspace.

This script owns the generated ``Submission/`` directories below ``LeanEval/``.
The adjacent ``Submission.lean`` files are small, hand-written theorem shims.
All other workspace files are trusted snapshots from leanprover/lean-eval and
must not be changed by this script.

Usage:
    python3 port_submission.py
    python3 port_submission.py --check
    python3 port_submission.py --problem jordan_curve --list-closure
    python3 port_submission.py --list
"""

from __future__ import annotations

import argparse
import dataclasses
import re
import shutil
import sys
import tomllib
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parent
WORKSPACES_ROOT = REPO_ROOT / "LeanEval"
GENERATED_HEADER = """/-
This file is generated by port_submission.py.  Edit the source module instead,
then run `python3 port_submission.py` from the repository root.
-/
"""


@dataclasses.dataclass(frozen=True)
class Problem:
    """How a source theorem is packaged for one lean-eval problem."""

    roots: tuple[str, ...]
    local_prefixes: tuple[str, ...]
    trusted_imports: tuple[tuple[str, str], ...] = ()
    note: str = ""

    @property
    def ready(self) -> bool:
        return bool(self.roots)


# Adding a future solution is deliberately small: give it one or more source
# root modules and list every top-level local module prefix reachable from them.
# Shared modules can occur in several problems; each payload receives the exact
# transitive closure it needs.
PROBLEMS: dict[str, Problem] = {
    "jordan_curve": Problem(
        roots=("JordanCurve",),
        local_prefixes=("JordanCurve",),
    ),
    "schoenflies": Problem(
        roots=(),
        local_prefixes=("Schoenflies", "JordanCurve"),
        note="workspace scaffold only; no full Schoenflies source theorem exists yet",
    ),
    "topological_classification_of_surfaces": Problem(
        roots=("ClassificationOfSurfaces.EvalStatement",),
        local_prefixes=("ClassificationOfSurfaces",),
        trusted_imports=((
            "ClassificationOfSurfaces.LeanEval.ChallengeDeps",
            "ChallengeDeps",
        ),),
    ),
}


IMPORT_RE = re.compile(
    r"^(?P<indent>\s*)import\s+"
    r"(?P<module>[A-Za-z_][A-Za-z0-9_']*(?:\.[A-Za-z_][A-Za-z0-9_']*)*)"
    r"(?P<tail>\s*(?:--.*)?)$"
)


class PackagingError(RuntimeError):
    pass


def module_path(module: str) -> Path:
    return REPO_ROOT.joinpath(*module.split(".")).with_suffix(".lean")


def is_local_module(module: str, prefixes: tuple[str, ...]) -> bool:
    return any(module == prefix or module.startswith(prefix + ".") for prefix in prefixes)


def imports(text: str) -> list[str]:
    result: list[str] = []
    for line in text.splitlines():
        if match := IMPORT_RE.match(line):
            result.append(match.group("module"))
    return result


def compute_closure(problem_id: str, problem: Problem) -> tuple[str, ...]:
    trusted = dict(problem.trusted_imports)
    seen: set[str] = set()
    pending = list(problem.roots)

    while pending:
        module = pending.pop()
        if module in seen or module in trusted:
            continue
        if not is_local_module(module, problem.local_prefixes):
            raise PackagingError(
                f"{problem_id}: configured root {module!r} is not under a local prefix"
            )

        source = module_path(module)
        if not source.is_file():
            raise PackagingError(f"{problem_id}: local module {module!r} has no file at {source}")

        seen.add(module)
        for imported in imports(source.read_text(encoding="utf-8")):
            if imported in trusted:
                continue
            if is_local_module(imported, problem.local_prefixes) and imported not in seen:
                pending.append(imported)

    return tuple(sorted(seen))


def rewrite_module(problem_id: str, problem: Problem, module: str,
                   closure: set[str]) -> str:
    trusted = dict(problem.trusted_imports)
    source = module_path(module)
    output: list[str] = []

    for line in source.read_text(encoding="utf-8").splitlines(keepends=True):
        match = IMPORT_RE.match(line.rstrip("\n"))
        if match is None:
            output.append(line)
            continue

        imported = match.group("module")
        replacement: str | None = None
        if imported in trusted:
            replacement = trusted[imported]
        elif is_local_module(imported, problem.local_prefixes):
            if imported not in closure:
                raise PackagingError(
                    f"{problem_id}: {module} imports local module {imported}, "
                    "but it is absent from the computed closure"
                )
            replacement = f"Submission.{imported}"

        if replacement is None:
            output.append(line)
            continue

        newline = "\n" if line.endswith("\n") else ""
        output.append(
            f"{match.group('indent')}import {replacement}{match.group('tail')}{newline}"
        )

    return GENERATED_HEADER + "".join(output)


def expected_payload(problem_id: str, problem: Problem) -> dict[Path, str]:
    closure = compute_closure(problem_id, problem)
    closure_set = set(closure)
    return {
        Path(*module.split(".")).with_suffix(".lean"):
            rewrite_module(problem_id, problem, module, closure_set)
        for module in closure
    }


def workspace_for(problem_id: str) -> Path:
    workspace = WORKSPACES_ROOT / problem_id
    lakefile = workspace / "lakefile.toml"
    if not lakefile.is_file():
        raise PackagingError(f"{problem_id}: missing trusted workspace file {lakefile}")
    with lakefile.open("rb") as handle:
        lake_name = tomllib.load(handle).get("name")
    if lake_name != problem_id:
        raise PackagingError(
            f"{problem_id}: {lakefile} has name={lake_name!r}; lean-eval will not discover it"
        )
    if not (workspace / "Submission.lean").is_file():
        raise PackagingError(f"{problem_id}: missing solver shim {workspace / 'Submission.lean'}")
    return workspace


def write_payload(problem_id: str, expected: dict[Path, str], dry_run: bool) -> None:
    workspace = workspace_for(problem_id)
    destination = workspace / "Submission"

    if destination.is_symlink():
        raise PackagingError(f"refusing to replace symlinked submission directory: {destination}")
    if dry_run:
        print(f"{problem_id}: would write {len(expected)} generated modules")
        return

    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir()
    for relative, text in expected.items():
        output = destination / relative
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text, encoding="utf-8")
    print(f"{problem_id}: wrote {len(expected)} generated modules")


def check_payload(problem_id: str, expected: dict[Path, str]) -> bool:
    destination = workspace_for(problem_id) / "Submission"
    actual_paths = {
        path.relative_to(destination)
        for path in destination.rglob("*.lean")
    } if destination.is_dir() else set()
    expected_paths = set(expected)
    clean = True

    for relative in sorted(expected_paths - actual_paths):
        print(f"{problem_id}: missing generated file Submission/{relative}")
        clean = False
    for relative in sorted(actual_paths - expected_paths):
        print(f"{problem_id}: unexpected generated file Submission/{relative}")
        clean = False
    for relative in sorted(expected_paths & actual_paths):
        actual = (destination / relative).read_text(encoding="utf-8")
        if actual != expected[relative]:
            print(f"{problem_id}: stale generated file Submission/{relative}")
            clean = False

    if clean:
        print(f"{problem_id}: payload is current ({len(expected)} modules)")
    return clean


def selected_problems(requested: list[str] | None) -> list[tuple[str, Problem]]:
    ids = requested if requested else list(PROBLEMS)
    selected: list[tuple[str, Problem]] = []
    for problem_id in ids:
        problem = PROBLEMS[problem_id]
        if not problem.ready:
            if requested:
                raise PackagingError(f"{problem_id}: {problem.note or 'no source roots configured'}")
            print(f"{problem_id}: skipped ({problem.note or 'not ready'})")
            continue
        selected.append((problem_id, problem))
    return selected


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--problem", action="append", choices=sorted(PROBLEMS),
        help="package only this problem (repeatable; defaults to every ready problem)",
    )
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    parser.add_argument("--dry-run", action="store_true", help="compute payloads without writing")
    parser.add_argument("--list", action="store_true", help="show configured problem status and exit")
    parser.add_argument(
        "--list-closure", action="store_true",
        help="print the source module closure instead of generating files",
    )
    args = parser.parse_args()

    if args.check and args.dry_run:
        parser.error("--check and --dry-run cannot be combined")

    if args.list:
        for problem_id, problem in PROBLEMS.items():
            status = "ready" if problem.ready else "scaffold"
            suffix = f" — {problem.note}" if problem.note else ""
            print(f"{problem_id}: {status}{suffix}")
        return 0

    try:
        selected = selected_problems(args.problem)
        clean = True
        for problem_id, problem in selected:
            if args.list_closure:
                print(f"[{problem_id}]")
                for module in compute_closure(problem_id, problem):
                    print(module)
                continue

            expected = expected_payload(problem_id, problem)
            if args.check:
                clean = check_payload(problem_id, expected) and clean
            else:
                write_payload(problem_id, expected, args.dry_run)
        return 0 if clean else 1
    except (OSError, PackagingError, tomllib.TOMLDecodeError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
